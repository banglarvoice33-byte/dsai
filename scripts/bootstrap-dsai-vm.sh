#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

APP_USER="${SUDO_USER:-$(whoami)}"
APP_GROUP="$(id -gn "$APP_USER" 2>/dev/null || id -gn)"
APP_ROOT="/home/${APP_USER}/dsai"
DOMAIN="${DSAI_DOMAIN:-dsai.banglarvoice24news.com}"
APP_PORT="${DSAI_APP_PORT:-3011}"
HOST_NAME="$(hostname)"
HOST_FQDN="$(hostname -f 2>/dev/null || hostname)"
NODE_BIN="$(command -v node || true)"
PNPM_BIN="$(command -v pnpm || true)"

[[ -n "$NODE_BIN" ]] || { echo "node is required" >&2; exit 1; }
[[ -n "$PNPM_BIN" ]] || { echo "pnpm is required" >&2; exit 1; }

sudo install -d -m 0755 -o "$APP_USER" -g "$APP_GROUP" \
  "$APP_ROOT" "$APP_ROOT/releases" "$APP_ROOT/shared" \
  "$APP_ROOT/backups" "$APP_ROOT/logs" "$APP_ROOT/run"
sudo install -d -m 0750 -o root -g "$APP_GROUP" /etc/dsai /var/log/dsai

write_assignment() {
  printf '%s=%q\n' "$1" "$2"
}

runtime_tmp="$(mktemp)"
env_tmp="$(mktemp)"
trap 'rm -f "$runtime_tmp" "$env_tmp"' EXIT
{
  echo '# Generated non-secret DSAI VM metadata.'
  write_assignment APP_NAME dsai
  write_assignment APP_USER "$APP_USER"
  write_assignment APP_GROUP "$APP_GROUP"
  write_assignment APP_ROOT "$APP_ROOT"
  write_assignment APP_PORT "$APP_PORT"
  write_assignment DOMAIN "$DOMAIN"
  write_assignment HOST_NAME "$HOST_NAME"
  write_assignment HOST_FQDN "$HOST_FQDN"
  write_assignment NODE_BIN "$NODE_BIN"
  write_assignment PNPM_BIN "$PNPM_BIN"
  write_assignment NODE_ENV production
} > "$runtime_tmp"
sudo install -m 0644 -o root -g root "$runtime_tmp" /etc/dsai/runtime.conf

printf '%s\n' 'Enter secrets locally. Input is hidden and values are never printed.' >&2
read -rsp 'DATABASE_URL [required]: ' DATABASE_URL; echo >&2
read -rsp 'JWT_SECRET [required]: ' JWT_SECRET; echo >&2
read -rsp 'VITE_APP_ID [required for OAuth]: ' VITE_APP_ID; echo >&2
read -rsp 'OAUTH_SERVER_URL [required for OAuth]: ' OAUTH_SERVER_URL; echo >&2
read -rsp 'VITE_OAUTH_PORTAL_URL [required for OAuth]: ' VITE_OAUTH_PORTAL_URL; echo >&2
read -rsp 'BUILT_IN_FORGE_API_URL [optional]: ' BUILT_IN_FORGE_API_URL; echo >&2
read -rsp 'BUILT_IN_FORGE_API_KEY [optional]: ' BUILT_IN_FORGE_API_KEY; echo >&2
read -rsp 'VITE_FRONTEND_FORGE_API_URL [optional]: ' VITE_FRONTEND_FORGE_API_URL; echo >&2
read -rsp 'VITE_FRONTEND_FORGE_API_KEY [optional]: ' VITE_FRONTEND_FORGE_API_KEY; echo >&2
read -rp 'DSAI_REQUIRE_FORGE [1=require Forge, 0=provider-gated; default 1]: ' DSAI_REQUIRE_FORGE
DSAI_REQUIRE_FORGE="${DSAI_REQUIRE_FORGE:-1}"
read -rp 'VITE_CAPTCHA_SITE_KEY [required in production]: ' VITE_CAPTCHA_SITE_KEY
read -rsp 'CAPTCHA_SECRET_KEY [required in production]: ' CAPTCHA_SECRET_KEY; echo >&2
read -rp "CAPTCHA_ALLOWED_HOSTNAME [default ${DOMAIN}]: " CAPTCHA_ALLOWED_HOSTNAME
CAPTCHA_ALLOWED_HOSTNAME="${CAPTCHA_ALLOWED_HOSTNAME:-$DOMAIN}"
read -rp 'CAPTCHA_VERIFY_URL [default Cloudflare Turnstile URL]: ' CAPTCHA_VERIFY_URL
CAPTCHA_VERIFY_URL="${CAPTCHA_VERIFY_URL:-https://challenges.cloudflare.com/turnstile/v0/siteverify}"
read -rp 'DSAI_CONTACT_EMAIL [optional]: ' DSAI_CONTACT_EMAIL
read -rp 'OWNER_OPEN_ID [optional]: ' OWNER_OPEN_ID
read -rp 'OWNER_NAME [optional]: ' OWNER_NAME

[[ -n "$DATABASE_URL" ]] || { echo 'DATABASE_URL is required; nothing written' >&2; exit 1; }
[[ -n "$JWT_SECRET" ]] || { echo 'JWT_SECRET is required; nothing written' >&2; exit 1; }
{
  echo '# Generated by scripts/bootstrap-dsai-vm.sh; keep private.'
  write_assignment NODE_ENV production
  write_assignment PORT "$APP_PORT"
  write_assignment APP_NAME dsai
  write_assignment APP_ROOT "$APP_ROOT"
  write_assignment DOMAIN "$DOMAIN"
  write_assignment HOST_NAME "$HOST_NAME"
  write_assignment HOST_FQDN "$HOST_FQDN"
  write_assignment DATABASE_URL "$DATABASE_URL"
  write_assignment JWT_SECRET "$JWT_SECRET"
  write_assignment VITE_APP_ID "$VITE_APP_ID"
  write_assignment OAUTH_SERVER_URL "$OAUTH_SERVER_URL"
  write_assignment VITE_OAUTH_PORTAL_URL "$VITE_OAUTH_PORTAL_URL"
  write_assignment BUILT_IN_FORGE_API_URL "$BUILT_IN_FORGE_API_URL"
  write_assignment BUILT_IN_FORGE_API_KEY "$BUILT_IN_FORGE_API_KEY"
  write_assignment DSAI_REQUIRE_FORGE "$DSAI_REQUIRE_FORGE"
  write_assignment VITE_FRONTEND_FORGE_API_URL "$VITE_FRONTEND_FORGE_API_URL"
  write_assignment VITE_FRONTEND_FORGE_API_KEY "$VITE_FRONTEND_FORGE_API_KEY"
  write_assignment VITE_CAPTCHA_SITE_KEY "$VITE_CAPTCHA_SITE_KEY"
  write_assignment CAPTCHA_SECRET_KEY "$CAPTCHA_SECRET_KEY"
  write_assignment CAPTCHA_ALLOWED_HOSTNAME "$CAPTCHA_ALLOWED_HOSTNAME"
  write_assignment CAPTCHA_VERIFY_URL "$CAPTCHA_VERIFY_URL"
  write_assignment DSAI_TEST_HOST "$DOMAIN"
  write_assignment DSAI_CONTACT_EMAIL "$DSAI_CONTACT_EMAIL"
  write_assignment OWNER_OPEN_ID "$OWNER_OPEN_ID"
  write_assignment OWNER_NAME "$OWNER_NAME"
} > "$env_tmp"
sudo install -m 0640 -o root -g "$APP_GROUP" "$env_tmp" /etc/dsai/dsai.env
sudo install -m 0640 -o root -g "$APP_GROUP" "$env_tmp" "$APP_ROOT/.env.production"
sudo chown -R "$APP_USER:$APP_GROUP" "$APP_ROOT"
sudo chmod 0640 "$APP_ROOT/.env.production"

printf 'Bootstrap complete. Non-secret runtime: /etc/dsai/runtime.conf\n'
printf 'Secret environment: /etc/dsai/dsai.env\n'
printf 'Application root: %s\n' "$APP_ROOT"
printf 'Application port: %s\n' "$APP_PORT"
printf 'Configured names only:\n'
sudo awk -F= '/^[A-Z0-9_]+=/ {print $1 "=[configured]"}' /etc/dsai/dsai.env
