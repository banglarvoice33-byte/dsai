-- DSAI Lead CRM: server-owned records, private attachments, auditable quality gates,
-- and an atomic UTC daily cap. This migration does not expose the service key to clients.

CREATE TABLE IF NOT EXISTS public.leads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  full_name varchar(160) NOT NULL CHECK (length(btrim(full_name)) BETWEEN 2 AND 160),
  email varchar(320),
  phone varchar(32),
  company varchar(180),
  source varchar(24) NOT NULL DEFAULT 'manual'
    CHECK (source IN ('manual', 'website', 'import', 'api', 'ai_enriched')),
  status varchar(24) NOT NULL DEFAULT 'new'
    CHECK (status IN ('new', 'contacted', 'qualified', 'converted', 'lost', 'archived')),
  notes varchar(4000),
  quality_gate jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT leads_contact_required CHECK (
    nullif(btrim(email), '') IS NOT NULL OR nullif(btrim(phone), '') IS NOT NULL
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS leads_owner_email_unique
  ON public.leads (owner_id, lower(email))
  WHERE email IS NOT NULL AND btrim(email) <> '';
CREATE INDEX IF NOT EXISTS leads_owner_created_idx
  ON public.leads (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS leads_owner_status_idx
  ON public.leads (owner_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.usage_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  service varchar(48) NOT NULL,
  action varchar(80) NOT NULL,
  quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  outcome varchar(24) NOT NULL CHECK (outcome IN ('success', 'rejected', 'failed')),
  request_id uuid,
  resource_id bigint,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS usage_logs_idempotency_unique
  ON public.usage_logs (owner_id, service, action, request_id)
  WHERE request_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS usage_logs_owner_service_created_idx
  ON public.usage_logs (owner_id, service, created_at DESC);
CREATE INDEX IF NOT EXISTS usage_logs_quota_lookup_idx
  ON public.usage_logs (owner_id, service, action, outcome, created_at DESC);

-- Private bucket: file bytes never become publicly readable. Direct client access is denied;
-- the trusted server uses its server-side Storage credential after authorization.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'lead-attachments',
  'lead-attachments',
  false,
  10485760,
  ARRAY['application/pdf', 'text/csv', 'image/jpeg', 'image/png']::text[]
